package me.apomazkin.quiz.chat.widget

import androidx.compose.animation.core.EaseInOutCubic
import androidx.compose.animation.core.Easing
import androidx.compose.ui.unit.dp

/**
 * Одна кривая на все движения чата: сдвиг соседей, въезд нового пузыря,
 * превращение кнопки в пузырь, полёт набранного ответа из поля в пузырь,
 * спуск аватара, разворот поля ввода. Tween
 * с плавным разгоном и торможением: пружина стартовала резко и читалась
 * как рывок.
 *
 * Для разглядывания анимаций длительность временно поднимали до 1,5–6 с
 * (2026-09-29); рабочее значение — 350 мс, паузы бота длиннее окна.
 */
internal object ChatMotion {
    const val DURATION_MS = 350
    val EASING: Easing = EaseInOutCubic

    /** Зазор между элементами ленты; участвует в дистанции спуска аватара по цепочке. */
    val ITEM_SPACING = 4.dp

    /** Отступ содержимого ленты от краёв; от него считается ширина копии текста в полёте. */
    val LIST_PADDING = 16.dp

    /**
     * Геометрия пузыря юзера: углы (хвост — правый нижний) и отступы
     * текста. Одна точка правды для пузыря в ленте и его летящей копии
     * ([FlightLayer]): на конце полёта они должны совпасть пиксель в пиксель.
     */
    val BUBBLE_CORNER = 20.dp
    val BUBBLE_TAIL_CORNER = 8.dp
    val BUBBLE_PADDING_H = 16.dp
    val BUBBLE_PADDING_V = 8.dp

    /** Широкая кнопка «Начать»: высота и доля ширины ленты; пузырь стартует из неё. */
    val START_BUTTON_HEIGHT = 48.dp
    const val START_BUTTON_WIDTH_FRACTION = 0.6f
    val START_BUTTON_CORNER = 24.dp

    /**
     * Фазы превращения кнопки в пузырь на линейном времени 0..1: сначала
     * гаснет соседний чип, потом пузырь перекрашивается; геометрия
     * (сдвиг, сжатие) — весь интервал. Внутри окна — [EASING].
     */
    const val GHOST_FADE_END = 0.45f
    const val RECOLOR_START = 0.3f

    /**
     * Полёт ответа из поля: одно окно на смену «чипы → плейсхолдер поля»:
     * чипы гаснут ровно пока проявляется плейсхолдер — одно время, одна
     * кривая, конец в один момент с прилётом текста на место пузыря (весь
     * полёт). Двигать оба движения — этой парой.
     */
    const val SWAP_START = 0f
    const val SWAP_END = 1f

    /**
     * Полёт ответа из поля: фон пузыря и цвет текста копии проявляются с
     * этой доли окна до конца полёта, синхронно (контраст по дороге не
     * проваливается: тёмный текст на слабом фоне → светлый на плотном).
     * Короткое окно (с [RECOLOR_START]) читалось как резкая смена
     * чёрного на белый.
     */
    const val FLIGHT_RECOLOR_START = 0f

    /** Доля окна [from, to] на линейном времени [t], сглаженная [EASING]. */
    fun window(t: Float, from: Float, to: Float): Float =
        EASING.transform(((t - from) / (to - from)).coerceIn(0f, 1f))
}
