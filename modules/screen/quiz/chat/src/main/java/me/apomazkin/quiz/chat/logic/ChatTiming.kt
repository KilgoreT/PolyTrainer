package me.apomazkin.quiz.chat.logic

/**
 * Темп чата в одном месте: длительность движения ленты и паузы «бот
 * думает» перед сообщением. Единственная точка, где слой логики знает
 * о темпе UI: паузы обязаны быть длиннее движения, иначе сообщения бота
 * встают друг на друга посреди анимации.
 *
 * Пауза считается от длительности с запасом на кадры старта анимации
 * (эффект стартует не в кадре апдейта, а через два-три) — см.
 * `ChatTimingTest`.
 */
internal object ChatTiming {
    /** Окно любого движения ленты (въезд, стыковка, морф, полёт, спуск аватара). */
    const val MOTION_DURATION_MS = 350

    /** Кадры между апдейтом состояния и первым кадром анимации, ~3 кадра при 60 Гц. */
    const val MOTION_LATENCY_MS = 50L

    const val BOT_PAUSE_MIN_MS = MOTION_DURATION_MS + MOTION_LATENCY_MS + 50L
    const val BOT_PAUSE_MAX_MS = 650L
}
